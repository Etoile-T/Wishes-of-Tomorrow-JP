#!/usr/bin/env python3
"""Japanese (kana) braille cells for the Braille font, shared by preproc and tests.

The font has all 64 six-dot cells; a byte's bits are the dots
1=0x01 4=0x02 2=0x04 5=0x08 3=0x10 6=0x20 (include/constants/characters.h).
Kana are written phonetically as in Japanese braille (particle は as わ, long
vowels as ー). Voiced/semi-voiced kana get a dakuten/handakuten prefix cell and
i-column kana followed by small ゃゅょ become a yoon prefix plus one cell.

usage: braille_ja.py header OUT.h   regenerate tools/preproc/braille_ja.h
       braille_ja.py encode TEXT    print the cell bytes for TEXT
       braille_ja.py decode HEX...  print kana for cell bytes (for review)
"""
import sys

D1, D2, D3, D4, D5, D6 = 0x01, 0x04, 0x10, 0x02, 0x08, 0x20
VOWELS = [D1, D1 | D2, D1 | D4, D1 | D2 | D4, D2 | D4]  # a i u e o
ROWS = {'': 0, 'k': D6, 's': D5 | D6, 't': D3 | D5, 'n': D3, 'h': D3 | D6, 'm': D3 | D5 | D6, 'r': D5}
DAKUTEN, HANDAKUTEN, YOON = D5, D6, D4
SPACE = 0x00

# kana -> (row, vowel index, mark) ; mark 0 plain, 1 dakuten, 2 handakuten
KANA = {}
for row, chars in [('', 'あいうえお'), ('k', 'かきくけこ'), ('s', 'さしすせそ'), ('t', 'たちつてと'),
                   ('n', 'なにぬねの'), ('h', 'はひふへほ'), ('m', 'まみむめも'), ('r', 'らりるれろ')]:
    for v, ch in enumerate(chars):
        KANA[ch] = (row, v, 0)
for row, chars, mark in [('k', 'がぎぐげご', 1), ('s', 'ざじずぜぞ', 1), ('t', 'だぢづでど', 1),
                         ('h', 'ばびぶべぼ', 1), ('h', 'ぱぴぷぺぽ', 2)]:
    for v, ch in enumerate(chars):
        KANA[ch] = (row, v, mark)
# kana with their own cells
SPECIAL = {'や': D3 | D4, 'ゆ': D3 | D4 | D6, 'よ': D3 | D4 | D5, 'わ': D3, 'を': D3 | D5,
           'ん': D3 | D5 | D6, 'っ': D2, 'ー': D2 | D5, '。': D2 | D5 | D6, '、': D5 | D6,
           '!': D2 | D3 | D5, ' ': SPACE}  # ASCII ! and space share the English cells
SMALL_Y = {'ゃ': 0, 'ゅ': 2, 'ょ': 4}  # vowel index after a yoon prefix

def hira(ch):
    code = ord(ch)
    return chr(code - 0x60) if 0x30A1 <= code <= 0x30F6 else ch

def encode(text):
    text = [hira(c) for c in text]
    out, i = [], 0
    while i < len(text):
        ch, nxt = text[i], text[i + 1] if i + 1 < len(text) else ''
        if ch in KANA and nxt in SMALL_Y:
            row, vowel, mark = KANA[ch]
            if vowel != 1:
                raise ValueError(f'yoon needs an i-column kana: {ch}{nxt}')
            out += [YOON | (DAKUTEN if mark == 1 else HANDAKUTEN if mark == 2 else 0),
                    ROWS[row] | VOWELS[SMALL_Y[nxt]]]
            i += 2
        elif ch in KANA:
            row, vowel, mark = KANA[ch]
            if mark:
                out.append(DAKUTEN if mark == 1 else HANDAKUTEN)
            out.append(ROWS[row] | VOWELS[vowel])
            i += 1
        elif ch in SPECIAL:
            out.append(SPECIAL[ch])
            i += 1
        else:
            raise ValueError(f'no Japanese braille cell for {ch!r}')
    return out

def decode(cells):
    plain = {ROWS[r] | VOWELS[v]: k for k, (r, v, m) in KANA.items() if m == 0}
    plain.update({v: k for k, v in SPECIAL.items()})
    out, prefix = [], None
    for c in cells:
        if c in (DAKUTEN, HANDAKUTEN, YOON, YOON | DAKUTEN, YOON | HANDAKUTEN) and prefix is None:
            prefix = c
            continue
        out.append(('[%02X]' % prefix if prefix is not None else '') + plain.get(c, '[%02X]' % c))
        prefix = None
    return ''.join(out)

def header():
    lines = ['// Generated by tools/localization/braille_ja.py; do not edit.',
             '// Japanese kana braille: code point, consonant-row dots, vowel index, mark',
             '// (0 plain, 1 dakuten, 2 handakuten) and, for kana with their own cell, the cell.',
             '#ifndef BRAILLE_JA_H', '#define BRAILLE_JA_H', '',
             'struct JapaneseBrailleKana { int code; unsigned char row; unsigned char vowel; unsigned char mark; };',
             'struct JapaneseBrailleCell { int code; unsigned char cell; };', '',
             'static const unsigned char kJapaneseBrailleVowels[5] = {%s};' % ', '.join('0x%02X' % v for v in VOWELS),
             'static const unsigned char kJapaneseBrailleDakuten = 0x%02X;' % DAKUTEN,
             'static const unsigned char kJapaneseBrailleHandakuten = 0x%02X;' % HANDAKUTEN,
             'static const unsigned char kJapaneseBrailleYoon = 0x%02X;' % YOON, '',
             'static const JapaneseBrailleKana kJapaneseBrailleKana[] = {']
    lines += ['    { 0x%04X, 0x%02X, %d, %d }, // %s' % (ord(k), ROWS[r], v, m, k) for k, (r, v, m) in KANA.items()]
    lines += ['};', '', 'static const JapaneseBrailleCell kJapaneseBrailleCells[] = {']
    lines += ['    { 0x%04X, 0x%02X }, // %s' % (ord(k), c, k) for k, c in SPECIAL.items() if ord(k) >= 0x80]
    lines += ['};', '', '// Small ya/yu/yo: vowel index used after a yoon prefix.',
              'static const JapaneseBrailleCell kJapaneseBrailleSmallY[] = {']
    lines += ['    { 0x%04X, %d }, // %s' % (ord(k), v, k) for k, v in SMALL_Y.items()]
    lines += ['};', '', '#endif // BRAILLE_JA_H', '']
    return '\n'.join(lines)

if __name__ == '__main__':
    cmd = sys.argv[1] if len(sys.argv) > 1 else ''
    if cmd == 'header':
        open(sys.argv[2], 'w').write(header())
    elif cmd == 'encode':
        print(' '.join('%02X' % c for c in encode(' '.join(sys.argv[2:]))))
    elif cmd == 'decode':
        print(decode([int(x, 16) for x in sys.argv[2:]]))
    else:
        sys.exit(__doc__)
